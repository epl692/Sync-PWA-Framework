/** The generated service worker (contracts/pwa-output.md). Plain JavaScript, no Workbox. */

export interface PrecacheFile {
  /** Relative to the worker (and the scope). */
  url: string;
  /** Content revision (SHA-256 hex). */
  revision: string;
}

export interface SwOptions {
  /** Identifies this build; becomes part of the cache name. */
  build: string;
  files: readonly PrecacheFile[];
}

export function generateServiceWorker(o: SwOptions): string {
  return `/* Generated by @sync/app-build. Do not edit. */
'use strict';
const BUILD = ${JSON.stringify(o.build)};
const CACHE = 'shell-' + BUILD;
const PRECACHE = ${JSON.stringify(o.files, null, 2)};
const SCOPE = self.registration.scope;
const abs = (u) => new URL(u, SCOPE).href;
const INDEX = abs('index.html');
const PRECACHED = new Set(PRECACHE.map((f) => abs(f.url)));
// A new worker waits until the app asks for it (message below) or every tab is closed.
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((f) => new Request(abs(f.url), { cache: 'reload' }))))
      .catch(async (error) => {
        // leave the previous version's cache alone and make this install fail
        await caches.delete(CACHE);
        throw error;
      }),
  );
});
self.addEventListener('activate', (event) => {
  // No clients.claim(): a page keeps one consistent version until it reloads.
  event.waitUntil(
    caches.keys().then((names) => Promise.all(names.filter((n) => n.startsWith('shell-') && n !== CACHE).map((n) => caches.delete(n)))),
  );
});
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'skipWaiting') self.skipWaiting();
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== new URL(SCOPE).origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.match(INDEX).then((hit) => hit || fetch(request)));
    return;
  }
  // runtime modules and everything else are left to the browser; the module loader owns its own cache
  const key = url.origin + url.pathname;
  if (!PRECACHED.has(key)) return;
  event.respondWith(caches.match(key).then((hit) => hit || fetch(request)));
});
`;
}
