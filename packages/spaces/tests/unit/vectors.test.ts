// T087: known-answer vectors, so another implementation can be checked byte for byte.
// Regenerate (only when a documented format change makes the old bytes wrong) with:  UPDATE_VECTORS=1 npx vitest run vectors
import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { b64urlEncode, base32, buildEnvelope, encodeEnvelope } from '@sync/core';
import { SPACE_CODEC_ID, SpaceCodec, parseHeader } from '../../src/codec/spaceCodec';
import { hex, unhex, utf8 } from '../../src/crypto/bytes';
import { keyIdOf } from '../../src/crypto/ids';
import { importAesKey, signBytes, verifySignature } from '../../src/crypto/suite';
import { unwrapKeys, wrapKeys } from '../../src/crypto/wrap';
import { signingInput } from '../../src/validators/spacesValidator';

const FILE = join(__dirname, '..', 'vectors', 'vectors.json');
const subtle = globalThis.crypto.subtle;

const SEED = unhex('9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60');
const PUB = unhex('d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a');
const KEY = unhex('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f');
const NONCE = unhex('a0a1a2a3a4a5a6a7a8a9aaab');
const SCOPE = base32(unhex('f0e0d0c0b0a090807060504030201000'));
const ENV = {
  v: 1,
  id: 'AUTHORAAAAAAAAAAAAAAAAAAAA:7',
  author: 'AUTHORAAAAAAAAAAAAAAAAAAAA',
  seq: 7,
  space: SCOPE,
  clock: '018bcfe56800-0003-AUTHORAAAAAAAAAAAAAAAAAAAA',
  codec: SPACE_CODEC_ID,
};
const BODY = {
  obj: 'OBJECT0000000000000000000A',
  op: 'create' as const,
  type: 'note',
  schemaVersion: 1,
  fields: { text: 'hello, world' },
};

async function build() {
  const keyId = hex(await keyIdOf(KEY));
  const aes = await importAesKey(KEY);
  const codec = new SpaceCodec(
    {
      scopeFor: () => SCOPE,
      writeKey: async () => ({ epoch: 3, keyId, key: aes }),
      readKey: async () => aes,
      used: async () => 1,
    },
    { nonce: () => NONCE },
  );
  const body = await codec.encode(BODY, { space: SCOPE, author: ENV.author, envelope: ENV });
  let env = buildEnvelope({
    author: ENV.author,
    seq: ENV.seq,
    space: SCOPE,
    clock: ENV.clock,
    codec: SPACE_CODEC_ID,
    body,
    sig: null,
  });
  const priv = await subtle.importKey(
    'jwk',
    { kty: 'OKP', crv: 'Ed25519', d: b64urlEncode(SEED), x: b64urlEncode(PUB) },
    { name: 'Ed25519' },
    false,
    ['sign'],
  );
  const signed = await signBytes(priv, signingInput(encodeEnvelope(env)));
  env = { ...env, sig: signed };
  return {
    keyId,
    aes,
    codec,
    body,
    signingInput: signingInput(encodeEnvelope(env)),
    sig: signed,
    raw: encodeEnvelope(env),
  };
}

async function grantVector() {
  const priv = unhex('77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a'); // RFC 7748 Alice
  const pub = unhex('8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a');
  const keyId = hex(await keyIdOf(KEY));
  const grant = await wrapKeys(SCOPE, { deviceId: 'RECIPIENTAAAAAAAAAAAAAAAAA', agreePub: pub }, [
    { epoch: 3, keyId, raw: KEY },
  ]);
  return {
    recipientPrivate: hex(priv),
    recipientPublic: hex(pub),
    deviceId: 'RECIPIENTAAAAAAAAAAAAAAAAA',
    grant,
    key: hex(KEY),
    keyId,
  };
}

describe('known-answer vectors', () => {
  if (process.env.UPDATE_VECTORS) {
    it('writes the vectors', async () => {
      const b = await build();
      const v = {
        note: 'Generated by tests/unit/vectors.test.ts. See specs/002-spaces-security-identity/contracts/crypto-envelope.md.',
        codec: {
          key: hex(KEY),
          scope: SCOPE,
          keyId: b.keyId,
          epoch: 3,
          nonce: hex(NONCE),
          envelope: ENV,
          body: BODY,
          bodyBytes: hex(
            b.raw
              ? await b.codec.encode(BODY, { space: SCOPE, author: ENV.author, envelope: ENV })
              : new Uint8Array(),
          ),
        },
        signature: {
          seed: hex(SEED),
          publicKey: hex(PUB),
          signingInput: hex(b.signingInput),
          signature: hex(b.sig),
          signedEnvelope: hex(b.raw),
        },
        grant: await grantVector(),
      };
      writeFileSync(FILE, JSON.stringify(v, null, 2) + '\n');
    });
  }

  it('reproduces the encrypted body byte for byte, and decrypts it', async () => {
    const v = JSON.parse(readFileSync(FILE, 'utf8'));
    const b = await build();
    const bytes = await b.codec.encode(BODY, { space: SCOPE, author: ENV.author, envelope: ENV });
    expect(hex(bytes)).toBe(v.codec.bodyBytes);
    expect(parseHeader(bytes)).toEqual({ fmt: 1, scope: SCOPE, epoch: v.codec.epoch, keyId: v.codec.keyId });
    expect(
      await b.codec.decode(unhex(v.codec.bodyBytes), { space: SCOPE, author: ENV.author, envelope: ENV }),
    ).toEqual({ ok: true, body: BODY });
  });

  it('reproduces the signing input and the Ed25519 signature, and verifies it', async () => {
    const v = JSON.parse(readFileSync(FILE, 'utf8'));
    const b = await build();
    expect(hex(b.signingInput)).toBe(v.signature.signingInput);
    expect(hex(b.sig)).toBe(v.signature.signature);
    expect(hex(b.raw)).toBe(v.signature.signedEnvelope);
    expect(
      await verifySignature(
        unhex(v.signature.publicKey),
        unhex(v.signature.signature),
        unhex(v.signature.signingInput),
      ),
    ).toBe(true);
    // the signing input is the canonical envelope with sig = null
    expect(new TextDecoder().decode(unhex(v.signature.signingInput))).toContain('"sig":null');
  });

  it('opens a stored key grant with the recipient key', async () => {
    const v = JSON.parse(readFileSync(FILE, 'utf8'));
    const key = await subtle.importKey(
      'jwk',
      {
        kty: 'OKP',
        crv: 'X25519',
        d: b64urlEncode(unhex(v.grant.recipientPrivate)),
        x: b64urlEncode(unhex(v.grant.recipientPublic)),
      },
      { name: 'X25519' },
      false,
      ['deriveBits'],
    );
    const out = await unwrapKeys(key, v.grant.deviceId, v.grant.grant);
    expect(out.map((o) => [o.epoch, o.keyId, hex(o.raw)])).toEqual([[3, v.grant.keyId, v.grant.key]]);
    void utf8;
  });
});
